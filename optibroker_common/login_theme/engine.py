"""Each company's Keycloak login and email theme, published to S3.

The base theme lives in src/keycloak_theme with @@TOKEN@@ placeholders. The
company's branding -- its name, colours, heading font, the wording on the login
and authenticator pages, and up to three images -- fills them in, and the
result is written to KEYCLOAK_THEMES_BUCKET under the realm's name: the folder
Keycloak's pods sync into their themes directory when they start. A theme
published while Keycloak is running is therefore only loaded at the next
restart; until then a realm bound to it gets Keycloak's built-in pages
(Keycloak logs "Failed to find LOGIN theme ... using built-in themes" and
carries on).

The branding is kept beside the theme as <theme>/branding.json, so the theme
can be republished from a newer base -- one company or all of them -- without
anyone re-entering it. Keycloak ignores the file.
"""
import base64
import hashlib
import json
import re
from pathlib import Path
from xml.etree import ElementTree

from optibroker_common.login_theme.text import OVERRIDABLE_KEYS, catalogue


BASE_THEME_DIR = Path(__file__).resolve().parent / "theme"

# Written into every generated login/theme.properties. Publishing refuses to
# overwrite a theme folder without it, so a hand-made theme is never replaced.
GENERATED_MARKER = "# Generated by optibroker-provisioner."

# The app's own fallback brand colour (--company-colour) when a company has none.
DEFAULT_COLOUR = "#4a9fc0"

BRANDING_FILE = "branding.json"

# Everything a company can change, with what it gets when it changes nothing.
# Blank colours are derived from company_colour; blank text hides its element.
DEFAULT_BRANDING = {
    "company_name": "",
    "company_colour": DEFAULT_COLOUR,   # buttons, links, step numbers
    "panel_colour": "",                 # the login page's left panel and the 2FA top bar
    "accent_colour": "",                # the rule under the login headline
    "background_colour": "#f7f6f1",     # the page behind the cards
    "heading_font": "serif",            # a FONTS key
    "body_font": "sans",
    "headline": "Bringing mortgages closer to home",
    "tagline": "Trusted mortgage support, every step of the way.",
    "welcome_title": "Welcome back",
    "welcome_subtitle": "Sign in to continue to your account.",
    "security_title": "Your information is protected",
    "security_text": "We use industry-standard security to keep your data safe.",
    "totp_title": "Set up your authenticator app",
    "totp_subtitle": "You'll use a code from your phone each time you sign in.",
    "footer_text": "All rights reserved.",
    "help_url": "",
    "show_illustration": True,
    "texts": {},                        # message key -> the company's own wording (see theme_text.py)
}

COLOUR_FIELDS = ("company_colour", "panel_colour", "accent_colour", "background_colour")
FONT_FIELDS = ("heading_font", "body_font")
MESSAGES_FILE = BASE_THEME_DIR / "login" / "messages" / "messages_en.properties"
TEXT_FIELDS = tuple(
    k for k, v in DEFAULT_BRANDING.items() if isinstance(v, str) and k not in COLOUR_FIELDS + FONT_FIELDS
)
MAX_TEXT = 300

SYSTEM_STACKS = {
    "serif": "'Iowan Old Style', 'Palatino Linotype', Palatino, Georgia, 'Times New Roman', serif",
    "sans": "Inter, system-ui, -apple-system, 'Segoe UI', Roboto, Arial, sans-serif",
}

# Fonts a company can pick for headings and body text. "serif" and "sans" are
# the visitor's own system fonts; the rest are bundled in src/keycloak_fonts
# and copied into the theme when chosen, so the login pages never call Google.
FONTS_DIR = Path(__file__).resolve().parent / "fonts"


def _load_fonts():
    fonts = {
        "serif": {"label": "Classic serif (system)", "category": "serif", "stack": SYSTEM_STACKS["serif"],
                  "heading_weight": 600, "faces": []},
        "sans": {"label": "Clean sans-serif (system)", "category": "sans", "stack": SYSTEM_STACKS["sans"],
                 "heading_weight": 600, "faces": []},
    }
    manifest = json.loads((FONTS_DIR / "manifest.json").read_text(encoding="utf-8"))
    for font_id, font in manifest.items():
        fonts[font_id] = {
            "label": font["family"], "category": font["category"], "heading_weight": font["heading_weight"],
            "stack": f"'{font['family']}', {SYSTEM_STACKS[font['category']]}", "faces": font["faces"],
            "family": font["family"],
        }
    return fonts


FONTS = _load_fonts()
FONT_FILES = {face["file"] for font in FONTS.values() for face in font["faces"]}


def font_faces_css(font_ids, url_prefix, query=""):
    """@font-face rules for the given fonts, their files at url_prefix + file name + query."""
    rules = []
    for font_id in dict.fromkeys(font_ids):
        font = FONTS[font_id]
        for face in font["faces"]:
            rules.append(
                f"@font-face {{ font-family: '{font['family']}'; font-style: normal; font-weight: {face['weight']}; "
                f"font-display: swap; src: url('{url_prefix}{face['file']}{query}') format('woff2'); "
                f"unicode-range: {face['unicode_range']}; }}"
            )
    return "\n".join(rules)


def font_files(branding):
    """The bundled font files the branding's heading and body fonts need."""
    return sorted({face["file"] for key in FONT_FIELDS for face in FONTS[branding[key]]["faces"]})


# Uploadable images: the logo beside the company name, an optional lighter one
# for the dark login panel, and a photo that replaces the panel's drawing.
IMAGE_SLOTS = ("logo", "panel_logo", "hero_image")
MAX_IMAGE_BYTES = 1_000_000
_IMAGE_TYPES = {"image/png": "png", "image/jpeg": "jpg", "image/webp": "webp", "image/svg+xml": "svg"}
_IMAGE_CONTENT_TYPES = {ext: mime for mime, ext in _IMAGE_TYPES.items()}

_CONTENT_TYPES = {".css": "text/css", ".ftl": "text/plain", ".properties": "text/plain",
                  ".json": "application/json", **{f".{e}": m for e, m in _IMAGE_CONTENT_TYPES.items()}}
_HEX = re.compile(r"^#?([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$")
_DATA_URL = re.compile(r"^data:([\w/+.-]+);base64,(.*)$", re.S)


def _rgb(colour):
    """(r, g, b) for a #rgb or #rrggbb colour, or None if it isn't one."""
    match = _HEX.match((colour or "").strip())
    if not match:
        return None
    digits = match.group(1)
    if len(digits) == 3:
        digits = "".join(c * 2 for c in digits)
    return tuple(int(digits[i:i + 2], 16) for i in (0, 2, 4))


def _hex(rgb):
    return "#" + "".join(f"{c:02x}" for c in rgb)


def _mix(rgb, towards, amount):
    """Move a colour `amount` (0-1) of the way towards another, as #rrggbb."""
    return _hex(round(c + (t - c) * amount) for c, t in zip(rgb, towards))


def _luminance(rgb):
    """WCAG relative luminance."""
    def channel(c):
        c /= 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * channel(rgb[0]) + 0.7152 * channel(rgb[1]) + 0.0722 * channel(rgb[2])


def _readable_on(rgb):
    """White or near-black, whichever reads better on the colour."""
    return "#ffffff" if _luminance(rgb) < 0.45 else "#111827"


def _text_shade(rgb):
    """The brand colour, darkened just enough to read as text on white (4.5:1).
    A pale brand colour still makes a pale button, but its links and labels stay legible."""
    for step in range(0, 21):
        shade = _rgb(_mix(rgb, (0, 0, 0), step * 0.05))
        if 1.05 / (_luminance(shade) + 0.05) >= 4.5:
            return _hex(shade)
    return "#111827"


def _message_value(text):
    """Escape text for a Keycloak messages .properties value.

    Keycloak formats messages with java.text.MessageFormat, so a single quote
    must be doubled and braces quoted; a backslash or line break would also
    change the meaning of the .properties line.
    """
    text = " ".join((text or "").split())
    text = text.replace("\\", "\\\\").replace("'", "''")
    return text.replace("{", "'{'").replace("}", "'}'")


def _message_unvalue(value):
    """The text a _message_value() result was made from."""
    value = value.replace("'{'", "{").replace("'}'", "}").replace("''", "'")
    return value.replace("\\\\", "\\")


def _safe_url(url):
    """An http(s) or mailto link, or "" -- never javascript: or similar."""
    url = (url or "").strip()
    if re.match(r"^(https?://|mailto:)[^\s\"'<>]+$", url, re.I) and len(url) <= MAX_TEXT:
        return url
    return ""


def normalise_branding(data):
    """Defaults overlaid with whatever `data` validly sets. Unknown keys are dropped,
    an invalid colour becomes the default (or blank, to be derived), text is
    trimmed to one line."""
    data = data or {}
    branding = dict(DEFAULT_BRANDING)
    for key in TEXT_FIELDS:
        if key in data and data[key] is not None:
            branding[key] = " ".join(str(data[key]).split())[:MAX_TEXT]
    branding["help_url"] = _safe_url(branding["help_url"])
    for key in COLOUR_FIELDS:
        rgb = _rgb(data.get(key))
        if rgb is not None:
            branding[key] = _hex(rgb)
    for key in FONT_FIELDS:
        if data.get(key) in FONTS:
            branding[key] = data[key]
    if "show_illustration" in data:
        branding["show_illustration"] = bool(data["show_illustration"])
    branding["texts"] = _normalise_texts(data.get("texts"))
    return branding


def text_catalogue():
    """Every page's editable wording, with its default (theme_text.PAGES)."""
    return catalogue(MESSAGES_FILE, DEFAULT_BRANDING)


def _default_texts():
    return {e["key"]: e["default"] for page in text_catalogue() for e in page["texts"] if "field" not in e}


def _normalise_texts(texts):
    """Only known keys, one line each, and only where they differ from the
    default -- so a company that changes nothing keeps following the theme."""
    if not isinstance(texts, dict):
        return {}
    defaults = _default_texts()
    kept = {}
    for key, value in texts.items():
        if key not in OVERRIDABLE_KEYS or not isinstance(value, str):
            continue
        value = " ".join(value.split())[:MAX_TEXT]
        if value and value != defaults.get(key):
            kept[key] = value
    return dict(sorted(kept.items()))


def theme_tokens(branding, images=None):
    """The values the base theme's @@TOKEN@@ placeholders are replaced with.
    `images` maps an image slot to its path under login/resources."""
    branding = normalise_branding(branding)
    images = images or {}
    white, black = (255, 255, 255), (0, 0, 0)
    brand = _rgb(branding["company_colour"])
    panel = _rgb(branding["panel_colour"]) or _rgb(_mix(brand, black, 0.12))
    accent = _rgb(branding["accent_colour"]) or _rgb(_mix(panel, white, 0.5))
    page = _rgb(branding["background_colour"])
    tokens = {
        "BRAND": _hex(brand),
        "BRAND_DARK": _mix(brand, black, 0.18),
        "BRAND_TEXT": _text_shade(brand),
        "BRAND_LIGHT": _mix(brand, white, 0.25),
        "BRAND_RGB": ",".join(str(c) for c in brand),
        "BRAND_TINT": _mix(brand, white, 0.94),
        "BRAND_TINT_2": _mix(brand, white, 0.86),
        "ON_BRAND": _readable_on(brand),
        "PANEL": _hex(panel),
        "PANEL_DARK": _mix(panel, black, 0.22),
        "ON_PANEL": _readable_on(panel),
        "ART_LINE": _mix(panel, white, 0.45),
        "ART_FILL": _mix(panel, white, 0.12),
        "ART_FILL_2": _mix(panel, white, 0.22),
        # The forgot/new password panel: waves from pale to the panel colour.
        "WAVE_0": _mix(panel, white, 0.8),
        "WAVE_1": _mix(panel, white, 0.66),
        "WAVE_2": _mix(panel, white, 0.48),
        "WAVE_3": _mix(panel, white, 0.28),
        "WAVE_4": _mix(panel, white, 0.06),
        "ACCENT": _hex(accent),
        "PAGE_BG": _hex(page),
        "SURFACE": _mix(page, black, 0.015),
        "HEADING_FONT": FONTS[branding["heading_font"]]["stack"],
        "HEADING_WEIGHT": str(FONTS[branding["heading_font"]]["heading_weight"]),
        "BODY_FONT": FONTS[branding["body_font"]]["stack"],
        # style.css lives in login/resources/css; the fonts beside it in ../fonts.
        "FONT_FACES": font_faces_css([branding["heading_font"], branding["body_font"]], "../fonts/"),
        "SHOW_ILLUSTRATION": "true" if branding["show_illustration"] else "false",
    }
    for key in TEXT_FIELDS:
        tokens[key.upper()] = _message_value(branding[key])
    for slot in IMAGE_SLOTS:
        tokens[slot.upper()] = _message_value(images.get(slot, ""))
    return tokens


def render_theme(branding, images=None):
    """The company's theme as {path inside the theme folder: bytes}."""
    tokens = theme_tokens(branding, images)
    sources = {path: path.read_text(encoding="utf-8")
               for path in sorted(BASE_THEME_DIR.rglob("*")) if path.is_file()}

    # Keycloak serves theme resources for 30 days at a URL that only changes
    # with the Keycloak version -- not on restart, not on publish -- so a
    # browser that saw the old stylesheet keeps it against new pages. Every
    # publish that changes anything gets its own ?v= on the stylesheet and fonts.
    digest = hashlib.sha256(json.dumps(tokens, sort_keys=True).encode("utf-8"))
    for path, text in sources.items():
        digest.update(path.relative_to(BASE_THEME_DIR).as_posix().encode("utf-8") + text.encode("utf-8"))
    version = digest.hexdigest()[:12]
    tokens["ASSET_VERSION"] = version
    tokens["FONT_FACES"] = font_faces_css(
        [normalise_branding(branding)[key] for key in FONT_FIELDS], "../fonts/", query=f"?v={version}",
    )

    files = {}
    for path, text in sources.items():
        for key, value in tokens.items():
            text = text.replace(f"@@{key}@@", value)
        leftover = re.findall(r"@@[A-Z0-9_]+@@", text)
        if leftover:
            raise RuntimeError(f"{path.name} has unfilled theme tokens: {sorted(set(leftover))}")
        files[path.relative_to(BASE_THEME_DIR).as_posix()] = text.encode("utf-8")

    # The company's own wording goes last: in a .properties file the last
    # definition of a key wins.
    texts = normalise_branding(branding)["texts"]
    if texts:
        rel = "login/messages/messages_en.properties"
        lines = "".join(f"{key}={_message_value(value)}\n" for key, value in texts.items())
        header = "\n\n# The company's own wording.\n"
        files[rel] = files[rel].rstrip(b"\r\n") + (header + lines).encode("utf-8")
    return files


def _check_svg(body):
    """Refuse an SVG that could run script. Theme images are served from
    Keycloak's own origin, so a scripted SVG opened directly would run there."""
    try:
        text = body.decode("utf-8")
    except UnicodeDecodeError as e:
        raise ValueError("The SVG is not UTF-8 text") from e
    lowered = text.lower()
    if "<!doctype" in lowered or "<!entity" in lowered or "javascript:" in lowered:
        raise ValueError("The SVG has a DOCTYPE, entities or a javascript: link")
    try:
        root = ElementTree.fromstring(text)
    except ElementTree.ParseError as e:
        raise ValueError("The SVG could not be read") from e
    if root.tag.rsplit("}", 1)[-1] != "svg":
        raise ValueError("The file is not an SVG")
    for el in root.iter():
        tag = el.tag.rsplit("}", 1)[-1].lower()
        if tag in {"script", "foreignobject", "iframe", "embed", "object"}:
            raise ValueError(f"The SVG contains a <{tag}> element")
        for name, value in el.attrib.items():
            attr = name.rsplit("}", 1)[-1].lower()
            if attr.startswith("on"):
                raise ValueError(f"The SVG has an event handler ({attr})")
            if attr == "href" and not value.strip().startswith(("#", "data:image/")):
                raise ValueError("The SVG links to another file")


def decode_image(data_url):
    """(extension, bytes) for an uploaded image given as a data: URL."""
    match = _DATA_URL.match((data_url or "").strip())
    if not match:
        raise ValueError("Images must be sent as a base64 data: URL")
    mime = match.group(1).lower()
    if mime not in _IMAGE_TYPES:
        raise ValueError(f"{mime} is not supported; use PNG, JPEG, WebP or SVG")
    try:
        body = base64.b64decode(match.group(2), validate=True)
    except ValueError as e:  # binascii.Error is a ValueError
        raise ValueError("The image is not valid base64") from e
    if not body:
        raise ValueError("The image is empty")
    if len(body) > MAX_IMAGE_BYTES:
        raise ValueError(f"Images must be {MAX_IMAGE_BYTES // 1_000_000} MB or smaller")
    if mime == "image/svg+xml":
        _check_svg(body)
    return _IMAGE_TYPES[mime], body
